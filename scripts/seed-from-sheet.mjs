// Pulls the public Google Sheet and writes:
//   src/data/companies.json  (offline fallback bundled into the site)
//   supabase/seed.sql        (initial rows for the Supabase `companies` table)
// Usage: npm run seed            (uses SHEET_ID below or env SHEET_ID)
import fs from 'node:fs';
import Papa from 'papaparse';

const SHEET_ID = process.env.SHEET_ID || '1fVKOd1KZotNep2suDczCnmWm2_UOq_vCmIvtzX7yytk';
const GID = process.env.SHEET_GID || '0';
const url = `https://docs.google.com/spreadsheets/d/${SHEET_ID}/export?format=csv&gid=${GID}`;

const res = await fetch(url);
if (!res.ok) throw new Error(`Sheet fetch failed: ${res.status}`);
const csv = await res.text();
const { data } = Papa.parse(csv, { skipEmptyLines: true });
const [, ...rows] = data;

const clean = (s) => (s ?? '').replace(/\r/g, '').trim();
const companies = rows
  .filter((r) => clean(r[0]))
  .map((r, i) => ({
    name: clean(r[0]),
    date_raw: clean(r[1]),
    role: clean(r[2]),
    ctc_raw: clean(r[3]),
    intake_raw: clean(r[4]),
    rounds: clean(r[5]),
    details: clean(r[6]),
    position: i,
    source: 'sheet',
  }));

fs.writeFileSync('src/data/companies.json', JSON.stringify(companies, null, 2) + '\n');

const seen = {};
for (const c of companies) {
  const base = c.name.trim().toLowerCase();
  seen[base] = (seen[base] ?? 0) + 1;
  c.sheet_key = `${base}#${seen[base]}`;
}
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const values = companies
  .map((c) => `  (${q(c.name)}, ${q(c.date_raw)}, ${q(c.role)}, ${q(c.ctc_raw)}, ${q(c.intake_raw)}, ${q(c.rounds)}, ${q(c.details)}, ${c.position}, 'sheet', ${q(c.sheet_key)})`)
  .join(',\n');
fs.writeFileSync(
  'supabase/seed.sql',
  `-- Generated by scripts/seed-from-sheet.mjs — run AFTER schema.sql\ninsert into public.companies (name, date_raw, role, ctc_raw, intake_raw, rounds, details, position, source, sheet_key) values\n${values}\non conflict (sheet_key) do nothing;\n`
);
// One file to paste into the Supabase SQL editor: schema + data.
const schema = fs.readFileSync('supabase/schema.sql', 'utf8') + '\n' + fs.readFileSync('supabase/chat.sql', 'utf8');
fs.writeFileSync('supabase/setup.sql', `-- schema.sql + chat.sql + seed.sql in one file. Paste all of it into Supabase → SQL Editor → Run.\n\n${schema}\n${fs.readFileSync('supabase/seed.sql', 'utf8')}`);
console.log(`Wrote ${companies.length} companies`);
